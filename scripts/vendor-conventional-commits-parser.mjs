#!/usr/bin/env node
/**
 * Writes templates/delivery-contract/scripts/vendor/conventional-commits-parser.cjs, the copy of
 * `@conventional-commits/parser` the delivery contract ships, from the pinned devDependency.
 *
 * WHY A VENDORED COPY. The PR Conventions workflow checks the squash message with the parser
 * release-please uses, and it runs that check before any install, like the body check beside it.
 * A consumer's own dependencies cannot supply it: the contract does not manage a consumer's
 * package.json. Shipping the parser as a managed file keeps the check install-free and pins the
 * exact version, and `delivery-contract check` reports a local edit to it as drift.
 *
 * WHICH VERSION. 0.4.1, the version release-please 17.6.0 resolves in the lockfile of
 * googleapis/release-please-action v5.0.0, the release-please the fleet pins. Both lockfiles carry
 * the same integrity:
 *   sha512-H2ZmUVt6q+KBccXfMBhbBF14NlANeqHTXL4qCL6QGbMzrc4HDXyzWuxPxPNbz71f/5UkR5DrycP5VO9u7crahg==
 * Move the devDependency only together with the release-please-action pin.
 *
 * WHAT IS COPIED. lib/codes.js, lib/type-checks.js, lib/scanner.js and lib/parser.js, each as
 * written upstream, wrapped as a module in one CommonJS file (`.cjs`, so it loads the same way
 * whatever `type` the consumer's package.json declares), plus the ISC license. index.js and
 * lib/utils.js are left out: release-please calls only the parser, and utils.js is the one file
 * with third-party dependencies. The output is run through prettier so it matches the managed
 * scripts beside it.
 *
 * Usage:
 *   node scripts/vendor-conventional-commits-parser.mjs          # write the vendored file
 *   node scripts/vendor-conventional-commits-parser.mjs --check  # exit 1 if it is out of date
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
export const VENDORED_PARSER_PATH = path.join(
  REPO_ROOT,
  "templates",
  "delivery-contract",
  "scripts",
  "vendor",
  "conventional-commits-parser.cjs",
);
const PACKAGE = "@conventional-commits/parser";
/** In dependency order; the `require` ids upstream uses between them. */
const MODULES = [
  { id: "./codes", file: "lib/codes.js" },
  { id: "./type-checks", file: "lib/type-checks.js" },
  { id: "./scanner", file: "lib/scanner.js" },
  { id: "./parser", file: "lib/parser.js" },
];

function packageRoot() {
  const require = createRequire(import.meta.url);
  return path.dirname(require.resolve(`${PACKAGE}/package.json`));
}

/**
 * Refuses a module that requires anything outside the vendored set, because the loader in the
 * output resolves only those ids: an upstream release that adds a dependency must fail here, at
 * generation, not when a consumer's workflow first loads the file.
 */
function assertSelfContained(id, source) {
  const known = new Set(MODULES.map((module) => module.id));
  for (const [, requested] of source.matchAll(
    /require\(\s*['"]([^'"]+)['"]\s*\)/g,
  )) {
    if (!known.has(requested)) {
      throw new Error(
        `${PACKAGE} ${id} requires ${requested}, which is not vendored — extend MODULES or stop vendoring`,
      );
    }
  }
}

/** The vendored file's bytes, as they should be on disk. */
export async function vendoredParserSource() {
  const root = packageRoot();
  const { version, license } = JSON.parse(
    readFileSync(path.join(root, "package.json"), "utf8"),
  );
  const licenseText = readFileSync(path.join(root, "LICENSE.txt"), "utf8")
    .trimEnd()
    .split("\n")
    .map((line) => ` * ${line}`.trimEnd())
    .join("\n");

  const definitions = MODULES.map(({ id, file }) => {
    const source = readFileSync(path.join(root, file), "utf8").trimEnd();
    assertSelfContained(id, source);
    return `  // ${PACKAGE}/${file}\n  ${JSON.stringify(id)}: function (module, exports, require) {\n${source}\n  },`;
  }).join("\n");

  const text = `/**
 * ${PACKAGE} ${version}, the parser release-please reads each commit with,
 * vendored so the PR Conventions workflow can run it without an install.
 *
 * GENERATED by scripts/vendor-conventional-commits-parser.mjs in minipuft/repository-standards,
 * which records why this version and which upstream files. Do not edit: that repository's tests
 * regenerate this file from the pinned package and fail on any difference, and
 * \`delivery-contract check\` reports a local edit as drift.
 *
 * License of the vendored code (${license}):
 *
${licenseText}
 */

const definitions = {
${definitions}
};

const loaded = {};
function load(id) {
  if (!(id in loaded)) {
    const module = { exports: {} };
    loaded[id] = module;
    definitions[id](module, module.exports, load);
  }
  return loaded[id].exports;
}

module.exports = { parser: load("./parser"), version: ${JSON.stringify(version)} };
`;
  const options = await prettier.resolveConfig(VENDORED_PARSER_PATH);
  return prettier.format(text, { ...options, filepath: VENDORED_PARSER_PATH });
}

async function main() {
  const expected = await vendoredParserSource();
  const relative = path.relative(REPO_ROOT, VENDORED_PARSER_PATH);
  if (process.argv.includes("--check")) {
    let actual = null;
    try {
      actual = readFileSync(VENDORED_PARSER_PATH, "utf8");
    } catch {
      // Reported below as out of date, the same as a stale copy.
    }
    if (actual !== expected) {
      console.error(
        `${relative} is not what the pinned ${PACKAGE} generates. Run: node scripts/vendor-conventional-commits-parser.mjs`,
      );
      process.exit(1);
    }
    console.log(`${relative} matches the pinned ${PACKAGE}.`);
    return;
  }
  writeFileSync(VENDORED_PARSER_PATH, expected);
  console.log(`wrote ${relative}`);
}

if (
  process.argv[1] &&
  import.meta.url === new URL(`file://${process.argv[1]}`).href
) {
  await main();
}
